// Regenerates src/lib/database.types.ts from the local stack's database, exactly
// as CI's e2e job does from the database supabase/migrations just built, so the
// committed copy and CI's differ only when the schema (or the CLI) has moved on;
// ci.yml warns when they do. The CLI prints its types unformatted; prettier,
// pinned exactly in package.json because a new version can lay the same types
// out differently, formats them.
//
// Needs Docker, and the stack running with this branch's migrations:
// `npx supabase@2 start`, then `npx supabase@2 db reset` if it last ran another
// branch (start reuses the old database). Without a stack, take the file from
// a CI run's migrated-schema artifact instead.
//
//   node --import tsx scripts/gen-db-types.ts
import { spawnSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { format } from 'prettier'

const FILE = 'src/lib/database.types.ts'
const HEADER = `// Generated by scripts/gen-db-types.ts from the public schema that
// supabase/migrations build: regenerate after every migration, never by hand.
// Application narrowing lives in db.ts.

`

// The CLI already installed (CI's, from setup-cli), else one fetched with npx.
const [cmd, ...pre] = spawnSync('supabase', ['--version']).status === 0 ? ['supabase'] : ['npx', '--yes', 'supabase@2']
const gen = spawnSync(cmd, [...pre, 'gen', 'types', 'typescript', '--local', '--schema', 'public'], {
  stdio: ['inherit', 'pipe', 'inherit'],
  encoding: 'utf8',
  // npx is npx.cmd on Windows and needs a shell (as in scripts/staging/up.ts).
  shell: cmd === 'npx' && process.platform === 'win32',
})
if (gen.status !== 0) throw new Error(`supabase gen types exited with ${gen.status}`)
writeFileSync(FILE, HEADER + (await format(gen.stdout, { parser: 'typescript', semi: false })))
console.log(`${FILE} regenerated`)
